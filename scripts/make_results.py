"""Generate results/summary.json and RESULTS.md from the raw
records, applying the frozen verdict rules of
PREREGISTRATION.md. Nothing in RESULTS.md is hand-typed; if a
cell is missing or failed, the affected verdicts come out
INCONCLUSIVE and the failure is stated, per the frozen rules.
"""
from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RESULTS = REPO / "results"
SEEDS = (42, 43, 44)
H2_BAND_PP = 5.0
H1_BAND = 0.10
H3_CONFIRM = 1.25
H3_REFUTE = 1.00


def verdict_h1(eff_b: float | None, eff_c: float | None) -> str:
    if eff_b is None or eff_c is None:
        return "INCONCLUSIVE"
    # The 1e-9 tolerance is float hygiene at the frozen boundary,
    # not a wider band.
    return "CONFIRMED" if abs(eff_c - eff_b) <= H1_BAND + 1e-9 else "REFUTED"


def verdict_h2(acc_a: float | None, acc_b: float | None, acc_c: float | None) -> str:
    if acc_a is None or acc_b is None or acc_c is None:
        return "INCONCLUSIVE"
    ok = abs(acc_b - acc_a) * 100 <= H2_BAND_PP + 1e-9 and abs(acc_c - acc_a) * 100 <= H2_BAND_PP + 1e-9
    return "CONFIRMED" if ok else "REFUTED"


def verdict_h3(ratio: float | None) -> str:
    if ratio is None:
        return "INCONCLUSIVE"
    if ratio >= H3_CONFIRM:
        return "CONFIRMED"
    if ratio <= H3_REFUTE:
        return "REFUTED"
    return "INCONCLUSIVE"


def _load(path: Path) -> dict | None:
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text())
    except json.JSONDecodeError:
        return None


def _ok(rec: dict | None) -> bool:
    return bool(rec) and rec.get("status") != "failed" and "throughput_samples_s" in rec


def main() -> int:
    runs: dict[str, dict[int, dict | None]] = {}
    for arm in ("a", "b", "c"):
        runs[arm] = {s: _load(RESULTS / "runs" / f"{arm}_s{s}.json") for s in SEEDS}

    complete = all(_ok(runs[arm][s]) for arm in runs for s in SEEDS)

    agg: dict[str, dict] = {}
    for arm in ("a", "b", "c"):
        good = [runs[arm][s] for s in SEEDS if _ok(runs[arm][s])]
        agg[arm] = {
            "runs_ok": len(good),
            "throughputs": [runs[arm][s]["throughput_samples_s"] if _ok(runs[arm][s]) else None for s in SEEDS],
            "accuracies": [runs[arm][s]["test_accuracy"] if _ok(runs[arm][s]) else None for s in SEEDS],
            "median_throughput": statistics.median([g["throughput_samples_s"] for g in good]) if len(good) == 3 else None,
            "mean_accuracy": statistics.fmean([g["test_accuracy"] for g in good]) if len(good) == 3 else None,
        }

    eff = {}
    base = agg["a"]["median_throughput"]
    for arm in ("b", "c"):
        med = agg[arm]["median_throughput"]
        eff[arm] = (med / (2 * base)) if (med is not None and base) else None

    p = _load(RESULTS / "inference" / "p.json")
    r = _load(RESULTS / "inference" / "r.json")
    inf_ok = bool(p and r and p.get("status") != "failed" and r.get("status") != "failed")
    ratio128 = None
    if inf_ok:
        ratio128 = r["cells"]["128"]["throughput_images_s"] / p["cells"]["128"]["throughput_images_s"]

    verdicts = {
        "H1": verdict_h1(eff["b"], eff["c"]) if complete else "INCONCLUSIVE",
        "H2": verdict_h2(agg["a"]["mean_accuracy"], agg["b"]["mean_accuracy"], agg["c"]["mean_accuracy"]) if complete else "INCONCLUSIVE",
        "H3": verdict_h3(ratio128) if inf_ok else "INCONCLUSIVE",
    }

    ckpt_sha = None
    a42 = runs["a"][42]
    if _ok(a42):
        ckpt_sha = a42.get("checkpoint_sha256")

    summary = {
        "training_complete": complete,
        "aggregates": agg,
        "scaling_efficiency": eff,
        "inference": {
            "complete": inf_ok,
            "pattern_r": r.get("pattern") if r else None,
            "throughput_ratio_128": ratio128,
            "p": p.get("cells") if p else None,
            "r": r.get("cells") if r else None,
        },
        "checkpoint_sha256": ckpt_sha,
        "verdicts": verdicts,
    }
    (RESULTS / "summary.json").write_text(json.dumps(summary, indent=2, sort_keys=True))

    lines: list[str] = []
    lines.append("# RESULTS: Ray Distributed Lab")
    lines.append("")
    lines.append("Generated by scripts/make_results.py from the raw records in")
    lines.append("results/. Verdict rules are the frozen ones in PREREGISTRATION.md.")
    lines.append("")
    lines.append("## Verdicts")
    lines.append("")
    d_h1 = None if eff["c"] is None or eff["b"] is None else abs(eff["c"] - eff["b"])
    lines.append(
        f"- H1 (Ray Train scaling parity with DDP, band plus or minus {H1_BAND}): "
        f"**{verdicts['H1']}**."
        + (f" Efficiency B {eff['b']:.3f}, C {eff['c']:.3f}, absolute difference {d_h1:.3f}."
           if d_h1 is not None else " A registered cell is missing.")
    )
    if agg["a"]["mean_accuracy"] is not None and agg["b"]["mean_accuracy"] is not None and agg["c"]["mean_accuracy"] is not None:
        db = (agg["b"]["mean_accuracy"] - agg["a"]["mean_accuracy"]) * 100
        dc = (agg["c"]["mean_accuracy"] - agg["a"]["mean_accuracy"]) * 100
        lines.append(
            f"- H2 (accuracy parity, band plus or minus {H2_BAND_PP} pp): **{verdicts['H2']}**."
            f" Mean test accuracy A {agg['a']['mean_accuracy']:.4f},"
            f" B {agg['b']['mean_accuracy']:.4f} ({db:+.2f} pp vs A),"
            f" C {agg['c']['mean_accuracy']:.4f} ({dc:+.2f} pp vs A)."
        )
    else:
        lines.append(f"- H2 (accuracy parity, band plus or minus {H2_BAND_PP} pp): **{verdicts['H2']}**. A registered cell is missing.")
    if ratio128 is not None:
        lines.append(
            f"- H3 (Ray serving throughput at batch 128 at least {H3_CONFIRM}x the plain loop): "
            f"**{verdicts['H3']}**. Measured ratio {ratio128:.3f}."
        )
    else:
        lines.append(f"- H3 (Ray serving throughput at batch 128): **{verdicts['H3']}**. Inference records are missing or failed.")
    lines.append("")
    lines.append("## Training runs (raw)")
    lines.append("")
    lines.append("| Arm | Seed | Throughput samples/s | Test accuracy | Counted steps | Step time s | Wall s |")
    lines.append("|---|---|---|---|---|---|---|")
    names = {"a": "A single", "b": "B DDP", "c": "C Ray Train"}
    for arm in ("a", "b", "c"):
        for s in SEEDS:
            rec = runs[arm][s]
            if _ok(rec):
                lines.append(
                    f"| {names[arm]} | {s} | {rec['throughput_samples_s']:.1f} | "
                    f"{rec['test_accuracy']:.4f} | {rec['counted_steps']} | "
                    f"{rec['step_time_s']:.1f} | {rec['wall_s']:.1f} |"
                )
            else:
                lines.append(f"| {names[arm]} | {s} | FAILED or missing | | | | |")
    lines.append("")
    lines.append("## Arm aggregates")
    lines.append("")
    lines.append("| Arm | Median throughput samples/s | Scaling efficiency | Mean test accuracy | Per-seed accuracy |")
    lines.append("|---|---|---|---|---|")
    for arm in ("a", "b", "c"):
        med = agg[arm]["median_throughput"]
        mean_acc = agg[arm]["mean_accuracy"]
        eff_s = "-" if arm == "a" or eff.get(arm) is None else f"{eff[arm]:.3f}"
        accs = ", ".join("-" if v is None else f"{v:.4f}" for v in agg[arm]["accuracies"])
        lines.append(
            f"| {names[arm]} | {'-' if med is None else f'{med:.1f}'} | {eff_s} | "
            f"{'-' if mean_acc is None else f'{mean_acc:.4f}'} | {accs} |"
        )
    lines.append("")
    lines.append("Baseline context (pytorch-depth-lab CPU arms, full 21,600-image train")
    lines.append("split, seed 42, same recipe family): C1 single epoch walls 263.6, 265.0,")
    lines.append("291.2 s, final validation accuracy 0.7600. C2 DDP epoch walls 346.1,")
    lines.append("301.5, 330.3 s, final validation accuracy 0.8559, a 9.59 pp divergence")
    lines.append("that failed its frozen plus or minus 1.0 pp window (its H7). Those runs")
    lines.append("used the full train split; this study uses the frozen 4,000-image")
    lines.append("subset, so absolute times are not comparable across the two studies.")
    lines.append("Efficiency and accuracy differences within this study are the evidence.")
    lines.append("")
    lines.append("## Inference cells (raw)")
    lines.append("")
    if inf_ok:
        lines.append(f"Arm R pattern used: {r.get('pattern')}. Arm P pattern: {p.get('pattern')}.")
        lines.append("")
        lines.append("| Arm | Batch | Throughput images/s | Latency p50 s | Latency p95 s | Batches |")
        lines.append("|---|---|---|---|---|---|")
        for label, rec in (("P plain loop", p), ("R Ray", r)):
            for bs in ("128", "32"):
                c = rec["cells"][bs]
                lines.append(
                    f"| {label} | {bs} | {c['throughput_images_s']:.1f} | "
                    f"{c['latency_p50_s']:.4f} | {c['latency_p95_s']:.4f} | {c['n_batches_measured']} |"
                )
        if ratio128 is not None:
            r32 = r["cells"]["32"]["throughput_images_s"] / p["cells"]["32"]["throughput_images_s"]
            lines.append("")
            lines.append(f"Throughput ratio R/P at batch 128: {ratio128:.3f}. At batch 32: {r32:.3f} (descriptive only, no verdict).")
    else:
        lines.append("Inference records are missing or failed; see results/logs/ and the")
        lines.append("driver summary. Per stop rule S1 the failure is reported, not hidden.")
    lines.append("")
    lines.append("## Provenance")
    lines.append("")
    lines.append(f"Checkpoint (arm A, seed 42) SHA-256: {ckpt_sha}.")
    lines.append("Versions: results/versions.json. Dataset: results/dataset.json.")
    lines.append("Per-cell logs: results/logs/. Producing driver: scripts/run_study.py.")
    lines.append("Claim boundary: the machine of record as amended (BlackBoxV2,")
    lines.append("8 cores, 14 GB RAM; Amendment A1 in PREREGISTRATION.md), the pinned")
    lines.append("versions, this dataset and recipe only.")
    lines.append("")
    (REPO / "RESULTS.md").write_text("\n".join(lines))
    print(json.dumps(verdicts, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
